/// <summary>
/// アイテムの種類。
/// 「剣なら攻撃力、盾なら防御力、薬なら回復」と、種類によって処理を分けるときに使う。
/// 文字列（"sword" など）で分けると打ち間違いに気付けないが、enum なら間違えたらコンパイルエラーになる。
/// </summary>
public enum ItemType
{
    Weapon,     // 武器：持っている間、攻撃力が上がる
    Armor,      // 防具：持っている間、受けるダメージが減る
    Potion      // 回復薬：拾った瞬間に HP が回復する（持ち物には残らない）
}
